std::optional<std::string> find_type(const RED4api::Expr& expr)
{
    auto result = std::visit([](const auto& arg) {

        std::string_view full_name = typeid(arg).name();
        
        auto start = full_name.find("::") + 2;
        auto type = full_name.substr(start);
        
        return std::move(type);
    }, expr);


    if (result.empty())
    {
        return std::nullopt;
    }

    return std::string(result);
};

